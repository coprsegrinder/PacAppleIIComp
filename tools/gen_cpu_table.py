"""TASK-033-4e3: writes port/src/core/cpu6502_table.inc (opcode -> mnemonic and addressing mode of the documented NMOS 6502 instructions) from tools/dis6502.py."""
import os, sys
sys.path.insert(0, os.path.dirname(__file__))
from dis6502 import OPS
MN = ['ADC', 'AND', 'ASL', 'BCC', 'BCS', 'BEQ', 'BIT', 'BMI', 'BNE', 'BPL', 'BRK', 'BVC', 'BVS', 'CLC', 'CLD', 'CLI', 'CLV', 'CMP', 'CPX', 'CPY', 'DEC', 'DEX', 'DEY', 'EOR', 'INC', 'INX', 'INY',
      'JMP', 'JSR', 'LDA', 'LDX', 'LDY', 'LSR', 'NOP', 'ORA', 'PHA', 'PHP', 'PLA', 'PLP', 'ROL', 'ROR', 'RTI', 'RTS', 'SBC', 'SEC', 'SED', 'SEI', 'STA', 'STX', 'STY', 'TAX', 'TAY', 'TSX', 'TXA', 'TXS', 'TYA']
MD = ['abs', 'abx', 'aby', 'acc', 'imm', 'imp', 'ind', 'izx', 'izy', 'rel', 'zp', 'zpx', 'zpy']
lines = ['// GENERATED by tools/gen_cpu_table.py: the documented NMOS 6502 instructions (mnemonic, addressing mode) by opcode; {-1, -1} = not a documented opcode.']
for op in range(256):
    if op in OPS:
        mn, md = OPS[op]
        lines.append('    {%d, %d},  // %02X %s %s' % (MN.index(mn), MD.index(md), op, mn, md))
    else:
        lines.append('    {-1, -1},  // %02X' % op)
open('port/src/core/cpu6502_table.inc', 'w').write('\n'.join(lines) + '\n')
print('ok', len(OPS))
