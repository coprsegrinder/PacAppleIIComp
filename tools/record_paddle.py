"""TASK-034-PADDLE: runs the ORIGINAL joystick routines ($701E paddle timing loop, $7041 direction decision, the whole input poll $6F5E in joystick mode) on the oracle for a grid of
paddle positions and writes the results as numbers for the C++ tests (port/tests/paddle_vectors.inc). The file holds only derived numbers (counts, flags, cycles), no original bytes.
Paddle model of the oracle (tools/apple2.py): a paddle of position v (0..255) reads "high" for v * 11 cycles after the trigger ($C070).
Usage: python -I tools/record_paddle.py [out-file]   (needs scratch/extract/PAC-MAN.1000.bin)"""
import os, sys
sys.path.insert(0, os.path.dirname(__file__))
from apple2 import Machine

BODY = open('scratch/extract/PAC-MAN.1000.bin', 'rb').read()
STUB = 0x0300      # JSR target ; NOP (the stop address)


def machine(f5, e8, p62):
    mc = Machine()
    mc.load(0x4000, BODY)
    mc.m[0xF5], mc.m[0xE8], mc.m[0x62], mc.m[0x63] = f5, e8, p62, 0
    return mc


def call(mc, target, px=127, py=127):
    mc.paddles[0], mc.paddles[1] = px, py
    mc.m[STUB:STUB + 4] = bytes([0x20, target & 0xFF, target >> 8, 0xEA])     # JSR target ; NOP
    c = mc.cpu
    c.pc, c.sp = STUB, 0xFD
    c.p &= ~1
    c.a = c.x = c.y = 0
    mc.paddle_start = None
    c0 = c.cycles
    mc.run(max_instr=100000, stop_pc=STUB + 3)
    return c.cycles - c0


def count_vector(v):
    """$701E alone with both paddles at v: X, Y and the cycles."""
    mc = machine(1, 0, 0)
    cyc = call(mc, 0x701E, v, v)
    return mc.cpu.x, mc.cpu.y, cyc


def decision(px, py, p62, e8):
    mc = machine(1, e8, p62)
    cyc = call(mc, 0x7041, px, py)
    c = mc.cpu
    return (c.p & 1), c.a, c.x, c.y, cyc


def poll_total(px, py, p62, e8, f5):
    """The whole poll $6F5E with no key waiting: cycles of the call and the resulting $63."""
    mc = machine(f5, e8, p62)
    mc.m[0x63] = 0x55
    mc.kbd = 0
    mc.buttons = [False, False, False]
    cyc = call(mc, 0x6F5E, px, py)
    return cyc, mc.m[0x63]


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else 'port/tests/paddle_vectors.inc'
    lines = ['// Generated by tools/record_paddle.py from runs of the original routines $701E / $7041 / $6F5E on the oracle (derived numbers only).',
             '// kCount[v] = {X, Y, cycles} of $701E with both paddles at position v; kDecision = {px, py, $62, $E8, carry, A, X, Y, cycles of JSR $7041, extra cycles of the whole poll against keyboard mode}.']
    lines.append('static const unsigned short kCount[256][3] = {')
    for v in range(256):
        x, y, cyc = count_vector(v)
        lines.append('    {%d, %d, %d},' % (x, y, cyc))
    lines.append('};')
    pos = sorted(set(list(range(0, 256, 17)) + [0, 1, 2, 3, 63, 64, 65, 66, 67, 68, 69, 70, 125, 126, 127, 128, 129, 163, 164, 165, 166, 167, 168, 200, 254, 255]))
    lines.append('static const unsigned short kDecision[][10] = {')
    n = 0
    for e8 in (0, 1):
        for p62 in (0, 1, 2, 3):
            kbd_base, _ = poll_total(127, 127, p62, e8, 0)
            for px in pos:
                for py in pos:
                    if e8 == 1 and (px not in (0, 127, 255) or py not in (0, 127, 255)):
                        continue
                    carry, a, x, y, cyc = decision(px, py, p62, e8)
                    tot, v63 = poll_total(px, py, p62, e8, 1)
                    # the poll's result: $63 is written unless carry is set
                    assert (v63 == 0x55) == bool(carry), (px, py, p62, e8, carry, v63)
                    if not carry:
                        assert v63 == a, (px, py, p62, e8, a, v63)
                    lines.append('    {%d, %d, %d, %d, %d, %d, %d, %d, %d, %d},' % (px, py, p62, e8, carry, a, x, y, cyc, tot - kbd_base))
                    n += 1
    lines.append('};')
    open(out, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
    print('wrote', out, n, 'decision vectors')


if __name__ == '__main__':
    main()
