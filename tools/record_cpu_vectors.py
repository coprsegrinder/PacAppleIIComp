"""TASK-034-CPU: expected results of the 6502 core for the C++ tests (port/tests/cpu_vectors.inc), computed with tools/cpu6502.py, the core that ran the original program for every recording of this project.
For every documented opcode, VECTORS_PER_OPCODE random starts (registers, flags, stack pointer, operand bytes, program counter near a page end for branches) with a memory whose bytes are a fixed function of
(seed, address) (so that the C++ test can rebuild it), plus an overlay of the instruction's own bytes and of everything the instruction writes. Per vector: the registers and flags after the instruction, its
cycles and up to three writes (address, value). Also the list of opcodes that are NOT documented (the C++ core must refuse those).
Row: { opcode, seed, a, x, y, p, sp, pc, operand1, operand2, | a', x', y', p', sp', pc', cycles, w1addr, w1val, w2addr, w2val, w3addr, w3val }   (-1 = no write)
Usage: python -I tools/record_cpu_vectors.py [out-file]"""
import os, random, sys
sys.path.insert(0, os.path.dirname(__file__))
from cpu6502 import CPU
from dis6502 import OPS

VECTORS_PER_OPCODE = 24


def memory_byte(seed, addr):
    """The fixed content of the memory: the same arithmetic in the C++ test (all values 32 bit)."""
    h = (addr * 0x9E3779B1 + seed * 0x85EBCA6B + 0x1234567) & 0xFFFFFFFF
    h ^= h >> 15
    h = (h * 0x2C1B3C6D) & 0xFFFFFFFF
    h ^= h >> 12
    return (h >> 8) & 0xFF


class Mem:
    def __init__(self, seed):
        self.seed = seed
        self.over = {}
        self.writes = []

    def read(self, a):
        a &= 0xFFFF
        return self.over[a] if a in self.over else memory_byte(self.seed, a)

    def write(self, a, v):
        a &= 0xFFFF
        self.over[a] = v & 0xFF
        self.writes.append((a, v & 0xFF))


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else 'port/tests/cpu_vectors.inc'
    rng = random.Random(6502)
    lines = ['// Generated by tools/record_cpu_vectors.py from runs of tools/cpu6502.py (derived numbers only); see that tool for the row layout.',
             'static const unsigned char kDocumented[256] = {']
    lines.append('    ' + ', '.join('1' if op in OPS else '0' for op in range(256)) + '};')
    lines.append('static const int kCpuVec[][23] = {')
    n = 0
    for op in sorted(OPS):
        mn, mode = OPS[op]
        for k in range(VECTORS_PER_OPCODE):
            seed = rng.getrandbits(24)
            mem = Mem(seed)
            cpu = CPU(mem)
            cpu.a, cpu.x, cpu.y = rng.getrandbits(8), rng.getrandbits(8), rng.getrandbits(8)
            cpu.p = (rng.getrandbits(8) & 0xCF) | 0x20            # N V - - D I Z C random; bit 5 set, B clear (as the chip's register shows it)
            cpu.sp = rng.getrandbits(8)
            if mode == 'rel':
                cpu.pc = (rng.randrange(2, 0xF0) << 8) | rng.choice([0xFD, 0xFE, 0xFF, 0x00, 0x01, rng.getrandbits(8)])
            else:
                cpu.pc = rng.randrange(0x0200, 0xE000)
            o1, o2 = rng.getrandbits(8), rng.getrandbits(8)
            if mode in ('abx', 'aby') and k % 2:
                o1 = 0xF0 | (o1 & 15)                           # base near the end of a page: crossings
            mem.over[cpu.pc] = op
            mem.over[(cpu.pc + 1) & 0xFFFF] = o1
            mem.over[(cpu.pc + 2) & 0xFFFF] = o2
            init = (op, seed, cpu.a, cpu.x, cpu.y, cpu.p, cpu.sp, cpu.pc, o1, o2)
            c0 = cpu.cycles
            mem.writes = []
            cpu.step()
            w = list(mem.writes)[:3]
            assert len(mem.writes) <= 3, (op, mem.writes)
            wf = []
            for i in range(3):
                wf += list(w[i]) if i < len(w) else [-1, -1]
            row = list(init) + [cpu.a, cpu.x, cpu.y, cpu.p, cpu.sp, cpu.pc, cpu.cycles - c0] + wf
            lines.append('    {' + ', '.join(str(v) for v in row) + '},')
            n += 1
    lines.append('};')
    open(out, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
    print('wrote', out, n, 'vectors,', 256 - len(OPS), 'undocumented opcodes')


if __name__ == '__main__':
    main()
