"""Generate the data-pack manifest for the C++ port: the address ranges of the program that are NOT code (port/src/datapack/manifest.cpp).
The output contains addresses and lengths only, no original bytes. Needs scratch/extract/PAC-MAN.1000.bin to run the analysis (development only).
Usage: python -I tools/make_manifest.py [--check]    --check compares the committed file with a fresh result instead of writing.
Also prints the SHA-256 of the concatenated data blobs (a hash of derived data, used by the real-image test).
"""
import hashlib, os, sys
sys.path.insert(0, os.path.dirname(__file__))
from classify_gaps import gaps_of
from recdis import analyse
from static_plus import table_targets, bytes_of

ORIGIN = 0x4000
OUT = os.path.join(os.path.dirname(__file__), '..', 'port', 'src', 'datapack', 'manifest.cpp')


def data_ranges(code_bytes, lo, hi):
    """[(address, length)] of every maximal run in [lo, hi) that is not code."""
    return [(a, b - a + 1) for a, b in gaps_of(code_bytes, lo, hi)]


def render(ranges):
    lines = ['// GENERATED by tools/make_manifest.py from the static + dynamic analysis. Addresses and lengths only: no original data.',
             '// Each range is a run of the relocated program ($4000-$A9FF) that is not code (docs/DATA_REGIONS.md).',
             '#include "datapack.h"', '', 'namespace pacman::datapack {', '', 'namespace {',
             'constexpr Range kRanges[] = {']
    for a, n in ranges:
        lines.append('    {0x%04X, %d},' % (a, n))
    lines += ['};', '}  // namespace', '', 'std::span<const Range> dataManifest() { return kRanges; }', '', '}  // namespace pacman::datapack', '']
    return '\n'.join(lines)


def content_hash(body, ranges):
    h = hashlib.sha256()
    for a, n in sorted(ranges):
        h.update(body[a - ORIGIN:a - ORIGIN + n])
    return h.hexdigest().upper()


def main():
    body = open('scratch/extract/PAC-MAN.1000.bin', 'rb').read()
    code, *_ = analyse(body, ORIGIN, [0x4027] + table_targets(body))
    ranges = data_ranges(bytes_of(code), ORIGIN, ORIGIN + len(body))
    text = render(ranges)
    total = sum(n for _, n in ranges)
    print('ranges: %d, data bytes: %d (program %d, code %d)' % (len(ranges), total, len(body), len(body) - total))
    print('SHA-256 of the concatenated data blobs: %s' % content_hash(body, ranges))
    if '--check' in sys.argv:
        current = open(OUT).read()
        print('committed manifest matches a fresh analysis:', current.replace('\r\n', '\n') == text)
        return 0 if current.replace('\r\n', '\n') == text else 1
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', newline='\n') as f:
        f.write(text)
    print('wrote', os.path.normpath(OUT))
    return 0


if __name__ == '__main__':
    sys.exit(main())
