"""TASK-030e4: mechanical transliteration of the 48 ghost decision routines ($8E1E-$96E7) into C++ (development tool; reads the extracted original from scratch/).
Writes port/src/core/ghostdecide_gen.cpp. The routines are small compare-and-branch trees (CMP/CPX/CPY against constants or the ghost position, LDA/EOR/SBC,
PHA/PLA, one JSR, two JMP, STA of the ghost's own direction): every instruction is emitted as a `case <original address>:` of one dispatch loop, registers A X Y and the
flags C Z N are C++ locals, and the only memory the routines touch ($70 ghost X, $71 ghost Y, $72 ghost direction, $62 Pac-Man direction, $69 Pac-Man tunnel flag) is the
DecisionEnv. Checked against the original on the oracle (tests/test_ghostdecide.cpp, tools/ghost_rules.py tables).
Usage: python -I tools/gen_ghost_decisions.py"""
import os, sys
sys.path.insert(0, os.path.dirname(__file__))
from recdis import analyse
from dis6502 import OPS

O = 0x4000
body = open('scratch/extract/PAC-MAN.1000.bin', 'rb').read()
tab = [body[0x8DBE - O + 2 * i] | body[0x8DBE - O + 2 * i + 1] << 8 for i in range(48)]
code = {}
for a in tab:
    c, *_ = analyse(body, O, [a])
    code.update(c)
ENV = {0x70: 'env.ghostX', 0x71: 'env.ghostY', 0x72: 'env.ghostDir', 0x62: 'env.pacDir', 0x69: 'env.pacTunnel'}


def operand(mode, raw):
    if mode == 'imm':
        return '0x%02X' % raw[1]
    if mode == 'zp':
        return ENV[raw[1]]
    raise SystemExit('mode %s' % mode)


out = []
w = out.append
w('// GENERATED by tools/gen_ghost_decisions.py (TASK-030e4) - do not edit. A mechanical transliteration into C++ of the 48 ghost decision routines of the original')
w('// ($8E1E-$96E7: %d instructions, %d bytes) that steer a ghost at a junction; see docs/GHOST_RULES.md. Case labels are the original addresses.' % (len(code), sum(code.values())))
w('#include "ghostdecide.h"')
w('')
w('namespace pacman::core {')
w('')
w('std::uint8_t ghostDecisionRun(std::uint16_t entry, std::uint8_t a, std::uint8_t x, std::uint8_t y, DecisionEnv& env) {')
w('    unsigned pc = entry;')
w('    std::uint16_t returns[8];')
w('    unsigned depth = 0;')
w('    std::uint8_t pushed[8];')
w('    unsigned pushes = 0;')
w('    bool c = false, z = false, n = false;')
w('    for (;;) {')
w('        switch (pc) {')
for ad in sorted(code):
    size = code[ad]
    raw = body[ad - O:ad - O + size]
    mn, mode = OPS[raw[0]]
    nxt = ad + size
    s = 'case 0x%04X: ' % ad
    cmp = lambda reg, v: '{ const unsigned r = static_cast<unsigned>(%s) - %s; c = %s >= %s; z = %s == %s; n = (r & 0x80u) != 0; }' % (reg, v, reg, v, reg, v)
    if mn == 'CMP':
        s += cmp('a', operand(mode, raw))
    elif mn == 'CPX':
        s += cmp('x', operand(mode, raw))
    elif mn == 'CPY':
        s += cmp('y', operand(mode, raw))
    elif mn == 'LDA':
        s += 'a = %s; z = a == 0; n = (a & 0x80u) != 0;' % operand(mode, raw)
    elif mn == 'EOR':
        s += 'a ^= %s; z = a == 0; n = (a & 0x80u) != 0;' % operand(mode, raw)
    elif mn == 'SBC':
        s += '{ const int r = static_cast<int>(a) - static_cast<int>(%s) - (c ? 0 : 1); c = r >= 0; a = static_cast<std::uint8_t>(r); z = a == 0; n = (a & 0x80u) != 0; }' % operand(mode, raw)
    elif mn == 'STA':
        assert raw[1] == 0x72
        s += 'env.ghostDir = a;'
    elif mn == 'TXA':
        s += 'a = x; z = a == 0; n = (a & 0x80u) != 0;'
    elif mn == 'TYA':
        s += 'a = y; z = a == 0; n = (a & 0x80u) != 0;'
    elif mn == 'TAX':
        s += 'x = a; z = x == 0; n = (x & 0x80u) != 0;'
    elif mn == 'SEC':
        s += 'c = true;'
    elif mn == 'NOP':
        s += ';'
    elif mn == 'PHA':
        s += 'if (pushes < 8) pushed[pushes++] = a;'
    elif mn == 'PLA':
        s += 'a = pushes > 0 ? pushed[--pushes] : 0; z = a == 0; n = (a & 0x80u) != 0;'
    elif mn == 'JMP':
        t = raw[1] | raw[2] << 8
        s += 'pc = 0x%04X; continue;' % t
    elif mn == 'JSR':
        t = raw[1] | raw[2] << 8
        s += 'if (depth < 8) returns[depth++] = 0x%04X; pc = 0x%04X; continue;' % (nxt, t)
    elif mn == 'RTS':
        s += 'if (depth == 0) return a; pc = returns[--depth]; continue;'
    elif mode == 'rel':
        t = (nxt + (raw[1] - 256 if raw[1] > 127 else raw[1])) & 0xFFFF
        cond = {'BEQ': 'z', 'BNE': '!z', 'BCS': 'c', 'BCC': '!c', 'BMI': 'n', 'BPL': '!n'}[mn]
        s += 'if (%s) { pc = 0x%04X; continue; }' % (cond, t)
    else:
        raise SystemExit('unhandled %s %s at %04X' % (mn, mode, ad))
    # the cycles of the instruction (TASK-034-TIMING): the routines only use immediate and zero-page operands, implied instructions, branches, one JSR and two JMPs
    if mode == 'rel':
        t = (nxt + (raw[1] - 256 if raw[1] > 127 else raw[1])) & 0xFFFF
        taken = 3 + (1 if (nxt >> 8) != (t >> 8) else 0)
        s = s.replace(' pc = 0x%04X; continue;' % t, ' env.cycles += %d; pc = 0x%04X; continue;' % (taken, t), 1)
        s += ' env.cycles += 2;'
        base = 2
    elif mn == 'JMP':
        base = 3
    elif mn == 'JSR' or mn == 'RTS':
        base = 6
    elif mn == 'PHA':
        base = 3
    elif mn == 'PLA':
        base = 4
    elif mode == 'imp':
        base = 2
    elif mode == 'imm':
        base = 2
    elif mode == 'zp':
        base = 3
    else:
        raise SystemExit('cycles of %s %s' % (mn, mode))
    s = s.replace('case 0x%04X: ' % ad, 'case 0x%04X: ' % ad + ('' if mode == 'rel' else 'env.cycles += %d; ' % base), 1)
    if mn not in ('JMP', 'JSR', 'RTS'):
        s += ' pc = 0x%04X; continue;' % nxt if not s.endswith('continue;') else ''
    w('            ' + s)
w('            default:')
w('                return a;   // not inside the routines: never reached with a valid entry')
w('        }')
w('    }')
w('}')
w('')
w('}  // namespace pacman::core')
open('port/src/core/ghostdecide_gen.cpp', 'w', newline='\n').write('\n'.join(out) + '\n')
print('wrote', len(code), 'instruction cases')
