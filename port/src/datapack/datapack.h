// The local data pack (decision D1-A, docs/DATAPACK_SPEC.md).
// A pack holds the data (never the code) of the verified game program, copied from the player's own disk image on the
// player's own machine. It is never committed or distributed. The loader accepts a pack only if it is intact and was
// built from the expected program.
#pragma once

#include <cstdint>
#include <span>
#include <string>
#include <vector>

#include "../verify/verify.h"

namespace pacman::datapack {

// A run of the relocated program ($4000-$A9FF) described by address and length only (no data).
struct Range {
    std::uint16_t address;
    std::uint16_t length;
};

// The runs of the program that are not code (generated by tools/make_manifest.py; see manifest.cpp).
std::span<const Range> dataManifest();

inline constexpr std::uint16_t kProgramOrigin = 0x4000;  // where the program runs after its startup copy

struct Blob {
    std::uint16_t address = 0;
    std::vector<std::uint8_t> bytes;
};

class Pack {
public:
    const std::vector<Blob>& blobs() const { return blobs_; }
    const std::string& programSha256() const { return programSha256_; }

    // The bytes [address, address+length) if one blob covers them completely, else an empty span.
    std::span<const std::uint8_t> find(std::uint16_t address, std::size_t length) const;

private:
    friend struct LoadResult;
    friend LoadResult loadPack(std::span<const std::uint8_t> bytes, const verify::Expected& expected);
    std::vector<Blob> blobs_;
    std::string programSha256_;
};

struct BuildResult {
    bool ok = false;
    std::string reason;
    std::vector<std::uint8_t> bytes;  // the pack file contents
};

struct LoadResult {
    bool ok = false;
    std::string reason;
    Pack pack;
};

// Builds a pack from a disk image. Refuses unless verify::verify() accepts the image (exact image or game program).
BuildResult buildPack(std::span<const std::uint8_t> image, const verify::Expected& expected, std::span<const Range> manifest);

// Checks the pack's structure, every blob's hash, the whole-file hash, and that it was built from the expected program.
LoadResult loadPack(std::span<const std::uint8_t> bytes, const verify::Expected& expected);

}  // namespace pacman::datapack
